function failHard(message) {
  console.error(`FATAL offline-20m-audit: ${message}`);
  process.exit(1);
}

function decodeAttr(value) {
  return value
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

function findRepeatedFingerprints(values) {
  const sorted = values.slice().sort();
  const repeated = new Set();
  for (let i = 1; i < sorted.length; i += 1) {
    if (sorted[i] === sorted[i - 1]) repeated.add(sorted[i]);
  }
  return repeated;
}

function writeQuarantineSeeds(opts) {
  const ids = [...new Set(opts.quarantineIds)].sort((a, b) => a - b);
  const body = `/**
 * AUTO-GENERATED by scripts/offline-20m-audit.mjs.
 * Stage-1 offline audit writes this file. Do not hand-edit.
 */
export const MANIFEST_COMPLETE = ${opts.complete ? 'true' : 'false'};
export const MANIFEST_CONTENT_VERSION = '${opts.contentVersion}';
export const MANIFEST_CORPUS_SIZE = ${opts.corpusSize};
export const MANIFEST_SCANNED = ${opts.scanned};
export const MANIFEST_IDENTITY_COMPLETE = ${opts.identityComplete ? 'true' : 'false'};
export const MANIFEST_DOCUMENT_COMPLETE = ${opts.documentComplete ? 'true' : 'false'};
export const MANIFEST_JACCARD_COMPLETE = ${opts.jaccardComplete ? 'true' : 'false'};
export const QUARANTINE_IDS: readonly number[] = [${ids.join(', ')}];
`;
  writeFileSync(join(projectRoot, 'functions', '_lib', 'quarantineSeeds.ts'), body);
}

function writeManifestBin(opts) {
  mkdirSync(dataDir, { recursive: true });
  const versionBytes = Buffer.from(opts.contentVersion, 'utf8');
  const ids = [...new Set(opts.quarantineIds)].sort((a, b) => a - b);
  const flags = (opts.complete ? 1 : 0) | (ids.length === 0 && opts.complete ? 2 : 0);
  const header = Buffer.alloc(4 + 2 + 4 + 1 + versionBytes.length + 1 + 4 + 4);
  let o = 0;
  header.write('IDXB', o, 4, 'ascii'); o += 4;
  header.writeUInt16LE(1, o); o += 2;
  header.writeUInt32LE(opts.corpusSize, o); o += 4;
  header.writeUInt8(versionBytes.length, o); o += 1;
  versionBytes.copy(header, o); o += versionBytes.length;
  header.writeUInt8(flags, o); o += 1;
  header.writeUInt32LE(opts.scanned, o); o += 4;
  header.writeUInt32LE(ids.length, o); o += 4;
  const idBuf = Buffer.alloc(ids.length * 4);
  ids.forEach((id, i) => idBuf.writeUInt32LE(id, i * 4));
  writeFileSync(join(dataDir, 'indexable_manifest.bin'), Buffer.concat([header.subarray(0, o), idBuf]));
  writeFileSync(join(projectRoot, 'out', 'reports', 'indexable_manifest.bin'), Buffer.concat([header.subarray(0, o), idBuf]));
}

function identityWorker() {
  const range = shardStemRange(SHARD, SHARDS, CORPUS_SIZE);
  const start = range.startIndex;
  const end = range.endIndex;
  const n = end - start;
  console.log(`[identity shard ${SHARD}/${SHARDS}] indexes ${start}..${end} (${n.toLocaleString()})`);
  const titleFp = new Float64Array(n);
  const descFp = new Float64Array(n);
  const h1Fp = new Float64Array(n);
  const ownerFp = new Float64Array(n);
  const stats = {
    shard: SHARD,
    start,
    end,
    scanned: 0,
    titleMin: Infinity,
    titleMax: 0,
    descriptionMin: Infinity,
    descriptionMax: 0,
    titleLengthFails: 0,
    descriptionLengthFails: 0,
    h1Mismatch: 0,
    trailingConjunction: 0,
    uniqueTokenFails: 0,
    maxTitleJaccard: 0,
    maxH1Jaccard: 0,
    titleJaccardFails: 0,
    h1JaccardFails: 0,
    failures: [],
  };
  const ring = [];
  const t0 = Date.now();
  for (let index = start; index < end; index += 1) {
    const page = pageForIndex(index);
    if (!page) {
      stats.failures.push({ index, reason: 'pageForIndex undefined' });
      continue;
    }
    const identity = buildIdentity(page);
    const { title, description, h1 } = identity;
    const offset = index - start;
    titleFp[offset] = fingerprint(title);
    descFp[offset] = fingerprint(description);
    h1Fp[offset] = fingerprint(h1);
    ownerFp[offset] = fingerprint(headingOwnerKey(page));
    stats.scanned += 1;
    stats.titleMin = Math.min(stats.titleMin, title.length);
    stats.titleMax = Math.max(stats.titleMax, title.length);
    stats.descriptionMin = Math.min(stats.descriptionMin, description.length);
    stats.descriptionMax = Math.max(stats.descriptionMax, description.length);

    const reject = (reason) => {
      if (stats.failures.length < MAX_FAIL_EXAMPLES) stats.failures.push({ index, slug: page.slug, reason });
    };

    if (title.length < 30 || title.length > 66) {
      stats.titleLengthFails += 1;
      reject(`title ${title.length}`);
    }
    if (description.length < 150 || description.length > 160) {
      stats.descriptionLengthFails += 1;
      reject(`meta ${description.length}`);
    }
    if (h1 !== title) {
      stats.h1Mismatch += 1;
      reject('H1 does not match Title exactly');
    }
    if (metaEndsWithTrailingConjunction(description)) {
      stats.trailingConjunction += 1;
      reject('Meta ends with trailing conjunction');
    }
    if (hasDuplicateContentTokens(title) || hasDuplicateContentTokens(h1) || hasDuplicateContentTokens(description)) {
      stats.uniqueTokenFails += 1;
      reject('uniqueTokens');
    }

    const localMod = index % MODIFIER_SPAN;
    ring[localMod] = identity;
    if (localMod === MODIFIER_SPAN - 1 || index === end - 1) {
      const count = localMod + 1;
      for (let m = 0; m < count; m += 1) {
        const left = ring[m];
        if (!left) continue;
        for (const nb of neighbourModifiers(m)) {
          if (nb >= count || !ring[nb]) continue;
          const tJ = ngramJaccard(left.title, ring[nb].title, 5);
          const hJ = ngramJaccard(left.h1, ring[nb].h1, 5);
          stats.maxTitleJaccard = Math.max(stats.maxTitleJaccard, tJ);
          stats.maxH1Jaccard = Math.max(stats.maxH1Jaccard, hJ);
          if (tJ > MAX_TITLE_H1_JACCARD) {
            stats.titleJaccardFails += 1;
            reject(`title Jaccard ${tJ.toFixed(4)} vs mod ${nb}`);
          }
          if (hJ > MAX_TITLE_H1_JACCARD) {
            stats.h1JaccardFails += 1;
            reject(`h1 Jaccard ${hJ.toFixed(4)} vs mod ${nb}`);
          }
        }
      }
    }

    if ((index - start + 1) % 250_000 === 0) {
      const secs = ((Date.now() - t0) / 1000).toFixed(0);
      console.log(`    shard ${SHARD} …${(index + 1).toLocaleString()} (${secs}s)`);
    }
  }

  mkdirSync(workDir, { recursive: true });
  writeFileSync(join(workDir, `fp-title-${SHARD}.bin`), Buffer.from(titleFp.buffer, titleFp.byteOffset, titleFp.byteLength));
  writeFileSync(join(workDir, `fp-desc-${SHARD}.bin`), Buffer.from(descFp.buffer, descFp.byteOffset, descFp.byteLength));
  writeFileSync(join(workDir, `fp-h1-${SHARD}.bin`), Buffer.from(h1Fp.buffer, h1Fp.byteOffset, h1Fp.byteLength));
  writeFileSync(join(workDir, `fp-owner-${SHARD}.bin`), Buffer.from(ownerFp.buffer, ownerFp.byteOffset, ownerFp.byteLength));
  writeFileSync(join(workDir, `identity-${SHARD}.json`), JSON.stringify(stats, null, 2));
  console.log(`[identity shard ${SHARD}] done ${stats.scanned.toLocaleString()} in ${((Date.now() - t0) / 1000).toFixed(0)}s, fails ${stats.failures.length}`);
}

function documentWorker() {
  const range = shardStemRange(SHARD, SHARDS, CORPUS_SIZE);
  let startStem = range.startStem;
  let endStem = range.endStem;
  if (STEM_LIMIT != null) {
    endStem = Math.min(endStem, startStem + STEM_LIMIT);
  }
  const progressFile = join(workDir, `document-${SHARD}.json`);
  mkdirSync(workDir, { recursive: true });
  const stats = existsSync(progressFile)
    ? JSON.parse(readFileSync(progressFile, 'utf8'))
    : {
      shard: SHARD,
      startStem,
      endStem,
      nextStem: startStem,
      scanned: 0,
      gateFails: 0,
      rustFails: 0,
      densityFails: 0,
      thinFails: 0,
      jaccardFails: 0,
      headingFails: 0,
      crossJobFails: 0,
      maxJaccard: 0,
      maxHeadingJaccard: 0,
      maxSharedHeadings: 0,
      minWords: Infinity,
      maxDensity: 0,
      comboBank: comboBankViolations(),
      quarantine: [],
      failures: [],
    };
  startStem = stats.nextStem ?? startStem;
  stats.endStem = endStem;
  const t0 = Date.now();
  console.log(`[document shard ${SHARD}/${SHARDS}] stems ${startStem}..${endStem} mode=${DOC_MODE}`);

  const reject = (index, slug, reason, extra = {}) => {
    stats.quarantine.push(index);
    if (stats.failures.length < MAX_FAIL_EXAMPLES) {
      stats.failures.push({ index, slug, reason, ...extra });
    }
  };

  for (let stem = startStem; stem < endStem; stem += 1) {
    const stemStart = stem * MODIFIER_SPAN;
    if (stemStart >= CORPUS_SIZE) break;
    const n = Math.min(MODIFIER_SPAN, CORPUS_SIZE - stemStart);
    const mods = DOC_MODE === 'adjacent'
      ? [...new Set([0, ...neighbourModifiers(0)])].filter((m) => m < n)
      : Array.from({ length: n }, (_, m) => m);

    const payloads = new Array(n);
    for (const m of mods) {
      const index = stemStart + m;
      const page = pageForIndex(index);
      if (!page) {
        reject(index, '', 'pageForIndex undefined');
        continue;
      }
      const html = renderProgrammaticPage(page, ORIGIN);
      const gate = edgeQualityGate(html, page);
      const body = extractMainText(html);
      const words = body.split(' ').filter(Boolean);
      const title = decodeAttr(html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] ?? '');
      const h1 = decodeAttr((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)?.[1] ?? '').replace(/<[^>]+>/g, ' '));
      const metaDesc = decodeAttr(html.match(/<meta\s+name=["']description["']\s+content=["']([^"']*)["']/i)?.[1] ?? '');
      const jsonLdText = extractJsonLdText(html);
      const rust = validateGoogleBingStandards({
        title, metaDesc, h1, bodyWords: words, jsonLdText,
      });
      const density = keywordDensity(words);
      stats.scanned += 1;
      stats.minWords = Math.min(stats.minWords, words.length);
      stats.maxDensity = Math.max(stats.maxDensity, density);

      if (!gate.ok) {
        stats.gateFails += 1;
        reject(index, page.slug, `gate: ${gate.issues.slice(0, 4).join('; ')}`);
        continue;
      }
      if (!rust.isIndexable) {
        stats.rustFails += 1;
        reject(index, page.slug, rust.rejectReason);
        continue;
      }
      if (words.length < MIN_WORDS) {
        stats.thinFails += 1;
        reject(index, page.slug, `thin ${words.length}`);
        continue;
      }
      if (density > MAX_KEYWORD_DENSITY) {
        stats.densityFails += 1;
        reject(index, page.slug, `density ${density.toFixed(4)}`);
        continue;
      }
      payloads[m] = {
        index,
        slug: page.slug,
        hashes: hash5grams(words),
        headings: extractHeadingSet(html),
      };
    }

    for (const m of mods) {
      const left = payloads[m];
      if (!left) continue;
      for (const nb of neighbourModifiers(m)) {
        if (nb >= n) continue;
        const right = payloads[nb];
        if (!right) continue;
        const jac = jaccard5gramEarlyExit(left.hashes, right.hashes, MAX_BODY_JACCARD);
        stats.maxJaccard = Math.max(stats.maxJaccard, jac.jaccard);
        if (jac.exceeded) {
          stats.jaccardFails += 1;
          reject(left.index, left.slug, `Jaccard ${jac.jaccard.toFixed(4)} > ${MAX_BODY_JACCARD}`, {
            sibling: right.slug,
            earlyExit: jac.earlyExit,
          });
          reject(right.index, right.slug, `Jaccard ${jac.jaccard.toFixed(4)} > ${MAX_BODY_JACCARD}`, {
            sibling: left.slug,
            earlyExit: jac.earlyExit,
          });
        }
        let shared = 0;
        let inter = 0;
        for (const h of left.headings) {
          if (right.headings.has(h)) {
            shared += 1;
            inter += 1;
          }
        }
        const union = left.headings.size + right.headings.size - inter;
        const hJac = union === 0 ? 0 : inter / union;
        stats.maxHeadingJaccard = Math.max(stats.maxHeadingJaccard, hJac);
        stats.maxSharedHeadings = Math.max(stats.maxSharedHeadings, shared);
        if (shared > 0 || hJac > (QUALITY_CONTRACT.maxSiblingHeadingJaccard ?? 0.05)) {
          stats.headingFails += 1;
          reject(left.index, left.slug, `shared H2/H3 ${shared}`, { sibling: right.slug });
        }
      }
    }

    // Cross-job heading uniqueness: same remainder, next pair (one page per stem).
    const probe = payloads[mods[0]];
    if (probe) {
      const pairIndex = Math.floor(probe.index / PER_PAIR);
      const remainder = probe.index % PER_PAIR;
      const otherIndex = ((pairIndex + 1) % PAIRS.length) * PER_PAIR + remainder;
      if (otherIndex < CORPUS_SIZE) {
        const other = pageForIndex(otherIndex);
        if (other) {
          const otherHtml = renderProgrammaticPage(other, ORIGIN);
          const otherHeads = extractHeadingSet(otherHtml);
          let shared = 0;
          for (const h of probe.headings) if (otherHeads.has(h)) shared += 1;
          if (shared > 0) {
            stats.crossJobFails += 1;
            reject(probe.index, probe.slug, `cross-job shared H2/H3 ${shared}`, { sibling: other.slug });
          }
        }
      }
    }

    stats.nextStem = stem + 1;
    if ((stem - range.startStem) % 25 === 0) {
      writeFileSync(progressFile, JSON.stringify(stats));
      const rate = stats.scanned / Math.max(0.001, (Date.now() - t0) / 1000);
      console.log(`    shard ${SHARD} stem ${stem}/${endStem} scanned ${stats.scanned.toLocaleString()} (${rate.toFixed(0)} pages/s)`);
    }
  }

  writeFileSync(progressFile, JSON.stringify(stats, null, 2));
  console.log(`[document shard ${SHARD}] done scanned ${stats.scanned.toLocaleString()} quarantined ${stats.quarantine.length}`);
}

function runRole(role, extraEnv) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['--import', 'tsx', fileURLToPath(import.meta.url)], {
      cwd: projectRoot,
      env: {
        ...process.env,
        OFFLINE_AUDIT_ROLE: role,
        ...extraEnv,
      },
      stdio: 'inherit',
    });
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${role} shard ${extraEnv.OFFLINE_AUDIT_SHARD} exited ${code}`));
    });
  });
}

async function coordinator() {
  mkdirSync(workDir, { recursive: true });
  mkdirSync(join(projectRoot, 'out', 'reports'), { recursive: true });
  console.log('[offline-20m-audit] Stage 1 — full-corpus Google/Bing audit');
  console.log(`  corpus ${CORPUS_SIZE.toLocaleString()}  shards ${SHARDS}  phase ${PHASE}  docMode ${DOC_MODE}`);
  console.log(`  agent ${AGENT_VERSION}  content ${CONTENT_VERSION}`);
  console.log(`  contract Jaccard ≤ ${QUALITY_CONTRACT.maxSiblingBodyJaccard}  density ≤ ${QUALITY_CONTRACT.maxKeywordDensity}  words ≥ ${QUALITY_CONTRACT.minWordCount}`);

  const comboIssues = comboBankViolations();
  if (comboIssues.length) {
    failHard(`combo bank cannot mint 5-grams: ${comboIssues.join('; ')}`);
  }

  const rustCheck = spawnSync(process.execPath, ['--import', 'tsx', join(__dirname, 'verify-seo-rules.mjs')], {
    cwd: projectRoot,
    stdio: 'inherit',
  });
  if (rustCheck.status !== 0) failHard('verify-seo-rules failed');

  const quarantine = new Set();
  const report = {
    generated: new Date().toISOString(),
    agentVersion: AGENT_VERSION,
    contentVersion: CONTENT_VERSION,
    corpusSize: CORPUS_SIZE,
    shards: SHARDS,
    phase: PHASE,
    docMode: DOC_MODE,
    identity: null,
    document: null,
    complete: false,
  };

  if (PHASE === 'all' || PHASE === 'identity') {
    const jobs = [];
    for (let shard = 0; shard < SHARDS; shard += 1) {
      jobs.push(runRole('identity-worker', { OFFLINE_AUDIT_SHARD: String(shard), OFFLINE_AUDIT_SHARDS: String(SHARDS) }));
    }
    await Promise.all(jobs);

    const identity = {
      scanned: 0,
      titleMin: Infinity,
      titleMax: 0,
      descriptionMin: Infinity,
      descriptionMax: 0,
      titleLengthFails: 0,
      descriptionLengthFails: 0,
      h1Mismatch: 0,
      trailingConjunction: 0,
      uniqueTokenFails: 0,
      maxTitleJaccard: 0,
      maxH1Jaccard: 0,
      titleJaccardFails: 0,
      h1JaccardFails: 0,
      duplicates: { title: 0, description: 0, h1: 0, owner: 0 },
      duplicateExamples: [],
      failures: [],
    };
    const titleFp = new Float64Array(CORPUS_SIZE);
    const descFp = new Float64Array(CORPUS_SIZE);
    const h1Fp = new Float64Array(CORPUS_SIZE);
    const ownerFp = new Float64Array(CORPUS_SIZE);
    let cursor = 0;
    for (let shard = 0; shard < SHARDS; shard += 1) {
      const stats = JSON.parse(readFileSync(join(workDir, `identity-${shard}.json`), 'utf8'));
      identity.scanned += stats.scanned;
      identity.titleMin = Math.min(identity.titleMin, stats.titleMin);
      identity.titleMax = Math.max(identity.titleMax, stats.titleMax);
      identity.descriptionMin = Math.min(identity.descriptionMin, stats.descriptionMin);
      identity.descriptionMax = Math.max(identity.descriptionMax, stats.descriptionMax);
      identity.titleLengthFails += stats.titleLengthFails;
      identity.descriptionLengthFails += stats.descriptionLengthFails;
      identity.h1Mismatch += stats.h1Mismatch;
      identity.trailingConjunction += stats.trailingConjunction;
      identity.uniqueTokenFails += stats.uniqueTokenFails;
      identity.maxTitleJaccard = Math.max(identity.maxTitleJaccard, stats.maxTitleJaccard);
      identity.maxH1Jaccard = Math.max(identity.maxH1Jaccard, stats.maxH1Jaccard);
      identity.titleJaccardFails += stats.titleJaccardFails;
      identity.h1JaccardFails += stats.h1JaccardFails;
      identity.failures.push(...stats.failures);
      for (const row of stats.failures) if (Number.isInteger(row.index)) quarantine.add(row.index);
      const n = stats.end - stats.start;
      const kinds = [
        ['title', titleFp],
        ['desc', descFp],
        ['h1', h1Fp],
        ['owner', ownerFp],
      ];
      for (const [name, dest] of kinds) {
        const buf = Buffer.from(readFileSync(join(workDir, `fp-${name}-${shard}.bin`)));
        const slice = new Float64Array(buf.buffer, buf.byteOffset, buf.byteLength / 8);
        dest.set(slice, stats.start);
      }
      cursor += n;
      void cursor;
    }

    const verifyDup = (kind, fingerprints, pick) => {
      const repeated = findRepeatedFingerprints(fingerprints);
      if (!repeated.size) return;
      const seen = new Map();
      for (let index = 0; index < CORPUS_SIZE; index += 1) {
        if (!repeated.has(fingerprints[index])) continue;
        const page = pageForIndex(index);
        if (!page) continue;
        const value = pick(page, index);
        const previous = seen.get(value);
        if (previous === undefined) {
          seen.set(value, page.slug);
          continue;
        }
        identity.duplicates[kind] += 1;
        quarantine.add(index);
        if (identity.duplicateExamples.length < 10) {
          identity.duplicateExamples.push({ kind, value, a: previous, b: page.slug });
        }
      }
    };
    verifyDup('title', titleFp, (page) => buildIdentity(page).title);
    verifyDup('description', descFp, (page) => buildIdentity(page).description);
    verifyDup('h1', h1Fp, (page) => buildIdentity(page).h1);
    verifyDup('owner', ownerFp, (page) => headingOwnerKey(page));
    identity.complete = identity.scanned === CORPUS_SIZE
      && identity.titleLengthFails === 0
      && identity.descriptionLengthFails === 0
      && identity.h1Mismatch === 0
      && identity.trailingConjunction === 0
      && identity.uniqueTokenFails === 0
      && identity.titleJaccardFails === 0
      && identity.h1JaccardFails === 0
      && identity.duplicates.title === 0
      && identity.duplicates.description === 0
      && identity.duplicates.h1 === 0
      && identity.duplicates.owner === 0;
    report.identity = identity;
    console.log(`[identity] scanned ${identity.scanned.toLocaleString()}  title ${identity.titleMin}-${identity.titleMax}  meta ${identity.descriptionMin}-${identity.descriptionMax}`);
    console.log(`[identity] h1≠title ${identity.h1Mismatch}  trailing ${identity.trailingConjunction}  uniqueTokens ${identity.uniqueTokenFails}`);
    console.log(`[identity] dups title/desc/h1/owner ${identity.duplicates.title}/${identity.duplicates.description}/${identity.duplicates.h1}/${identity.duplicates.owner}`);
    console.log(`[identity] neighbour title Jaccard max ${identity.maxTitleJaccard.toFixed(4)}  h1 ${identity.maxH1Jaccard.toFixed(4)}`);
  }

  if (PHASE === 'all' || PHASE === 'document') {
    const jobs = [];
    for (let shard = 0; shard < SHARDS; shard += 1) {
      jobs.push(runRole('document-worker', {
        OFFLINE_AUDIT_SHARD: String(shard),
        OFFLINE_AUDIT_SHARDS: String(SHARDS),
        OFFLINE_AUDIT_MOD_MODE: DOC_MODE,
        ...(STEM_LIMIT != null ? { OFFLINE_AUDIT_STEM_LIMIT: String(STEM_LIMIT) } : {}),
      }));
    }
    await Promise.all(jobs);
    const document = {
      scanned: 0,
      expected: DOC_MODE === 'all' ? CORPUS_SIZE : stemCount(CORPUS_SIZE) * 3,
      gateFails: 0,
      rustFails: 0,
      densityFails: 0,
      thinFails: 0,
      jaccardFails: 0,
      headingFails: 0,
      crossJobFails: 0,
      maxJaccard: 0,
      maxHeadingJaccard: 0,
      maxSharedHeadings: 0,
      minWords: Infinity,
      maxDensity: 0,
      failures: [],
    };
    for (let shard = 0; shard < SHARDS; shard += 1) {
      const stats = JSON.parse(readFileSync(join(workDir, `document-${shard}.json`), 'utf8'));
      document.scanned += stats.scanned;
      document.gateFails += stats.gateFails;
      document.rustFails += stats.rustFails;
      document.densityFails += stats.densityFails;
      document.thinFails += stats.thinFails;
      document.jaccardFails += stats.jaccardFails;
      document.headingFails += stats.headingFails;
      document.crossJobFails += stats.crossJobFails;
      document.maxJaccard = Math.max(document.maxJaccard, stats.maxJaccard || 0);
      document.maxHeadingJaccard = Math.max(document.maxHeadingJaccard, stats.maxHeadingJaccard || 0);
      document.maxSharedHeadings = Math.max(document.maxSharedHeadings, stats.maxSharedHeadings || 0);
      document.minWords = Math.min(document.minWords, stats.minWords || Infinity);
      document.maxDensity = Math.max(document.maxDensity, stats.maxDensity || 0);
      document.failures.push(...(stats.failures || []));
      for (const id of stats.quarantine || []) quarantine.add(id);
    }
    document.complete = DOC_MODE === 'all'
      && !STEM_LIMIT
      && document.scanned >= CORPUS_SIZE
      && document.gateFails === 0
      && document.rustFails === 0
      && document.jaccardFails === 0
      && document.headingFails === 0
      && document.crossJobFails === 0
      && document.thinFails === 0
      && document.densityFails === 0;
    report.document = document;
    console.log(`[document] scanned ${document.scanned.toLocaleString()}  minWords ${document.minWords}  maxDensity ${document.maxDensity.toFixed(4)}`);
    console.log(`[document] Jaccard max ${document.maxJaccard.toFixed(4)}  heading ${document.maxHeadingJaccard.toFixed(4)}  shared ${document.maxSharedHeadings}`);
    console.log(`[document] fails gate/rust/jaccard/heading/cross ${document.gateFails}/${document.rustFails}/${document.jaccardFails}/${document.headingFails}/${document.crossJobFails}`);
  }

  const identityComplete = Boolean(report.identity?.complete);
  const documentComplete = Boolean(report.document?.complete);
  const complete = identityComplete && documentComplete && quarantine.size === 0
    ? true
    : identityComplete && documentComplete;
  // complete means every URL was decided, even if some were quarantined
  const decided = identityComplete && documentComplete;
  report.quarantineCount = quarantine.size;
  report.complete = decided;
  report.indexableCount = decided ? CORPUS_SIZE - quarantine.size : null;

  writeQuarantineSeeds({
    complete: decided,
    contentVersion: decided ? CONTENT_VERSION : '',
    corpusSize: CORPUS_SIZE,
    scanned: report.document?.scanned || report.identity?.scanned || 0,
    identityComplete,
    documentComplete,
    jaccardComplete: documentComplete,
    quarantineIds: [...quarantine],
  });
  writeManifestBin({
    complete: decided,
    contentVersion: CONTENT_VERSION,
    corpusSize: CORPUS_SIZE,
    scanned: report.document?.scanned || report.identity?.scanned || 0,
    quarantineIds: [...quarantine],
  });
  writeFileSync(join(projectRoot, 'out', 'reports', 'offline-20m-audit.json'), JSON.stringify(report, null, 2));
  console.log(`[offline-20m-audit] complete=${decided} identity=${identityComplete} document=${documentComplete} quarantine=${quarantine.size}`);
  if (!identityComplete || (PHASE !== 'identity' && !documentComplete)) {
    console.error('INCOMPLETE — manifest will not 404 the factory as a band until both phases finish.');
    process.exitCode = 1;
    return;
  }
  if (quarantine.size) {
    console.error(`QUARANTINE ${quarantine.size} URL(s) — 404 seeds written to the manifest.`);
    process.exitCode = 1;
    return;
  }
  console.log('PASS — all 20M URLs are indexable under the Google/Bing contract.');
}

if (ROLE === 'identity-worker') identityWorker();
else if (ROLE === 'document-worker') documentWorker();
else {
  coordinator().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
