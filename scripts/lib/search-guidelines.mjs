/**
 * scripts/lib/search-guidelines.mjs
 * ============================================================================
 * The rulebook the AI Quality & Indexing agent enforces.
 *
 * Every rule below is a machine-checkable restatement of a published
 * requirement from one of two sources:
 *
 *   BING — Bing Webmaster Guidelines (crawling, indexing, ranking, and
 *          grounding/Copilot eligibility). Section numbers refer to the
 *          numbered sections of those guidelines.
 *   GOOGLE — Google Search Console "Page indexing" report reasons, i.e. the
 *          concrete states that keep a URL out of the index ("Duplicate
 *          without user-selected canonical", "Crawled - currently not
 *          indexed", "Soft 404", "URL marked noindex", …).
 *
 * Two profiles exist because two different artefacts are audited:
 *
 *   'edge'   the HTML functions/[[path]].ts serves for the 20M programmatic
 *            /k/ URLs. Fully generated by us, so every rule is enforced
 *            exactly — a violation is a build failure.
 *   'static' the Next.js static export under out/. Hand-authored and
 *            component-driven, so metadata length rules keep the wider
 *            tolerance the crawlers themselves apply, and failures degrade to
 *            soft isolation rather than a broken build.
 *
 * Everything here is pure string/regex analysis: no network, no LLM API, no
 * Cloudflare Function invocation. It costs build CPU and nothing else.
 */

/** Bing recommends 150–160 characters; anything shorter is reported as "too short". */
export const DESCRIPTION_TARGET_MIN = 150;
export const DESCRIPTION_TARGET_MAX = 160;

/**
 * Bing Webmaster Tools: "Change the title length to be less than 70 characters."
 * Exact 70-character titles were still flagged, so 69 is the hard ceiling. The
 * budget the corpus is built to is 66: three characters of slack mean a later
 * edit, or a report that counts differently, cannot put those URLs back in the
 * "title too long" list — and a title this short survives Google's SERP
 * truncation, which is worth more in clicks than the extra words.
 */
export const TITLE_MAX = 66;
export const TITLE_MIN = 30;

/** Below this a page reads as thin content and tends to sit in "Crawled - currently not indexed". */
export const MIN_WORD_COUNT = 1700;
export const MAX_KEYWORD_DENSITY = 0.025;
export const MAX_TITLE_H1_JACCARD = 0.10;

export const PROFILES = {
  edge: {
    titleMin: TITLE_MIN,
    titleMax: TITLE_MAX,
    descriptionMin: DESCRIPTION_TARGET_MIN,
    descriptionMax: DESCRIPTION_TARGET_MAX,
    minWordCount: MIN_WORD_COUNT,
    minInternalLinks: 14,
    minJsonLd: 3,
  },
  static: {
    titleMin: 20,
    // The hand-written pages (home, tools, guides, legal) are audited against
    // Bing's hard ceiling rather than the corpus budget: they are a few dozen
    // titles a person can read, not 20M generated ones.
    titleMax: 69,
    descriptionMin: 120,
    descriptionMax: 165,
    minWordCount: 600,
    minInternalLinks: 5,
    minJsonLd: 1,
  },
};

