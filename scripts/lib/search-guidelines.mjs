/** Human-readable digest, embedded in the agent's build report. */
export function guidelineDigest() {
  return [
    ...DOCUMENT_RULES.map((r) => `[${r.severity}] ${r.id} — ${r.requirement} (${r.source})`),
    ...CORPUS_RULES.map((r) => `[${r.severity}] ${r.id} — ${r.requirement} (${r.source})`),
  ];
}

/**
 * Runs every document rule. `signals` comes from
 * scripts/lib/ai-quality-scoring.mjs → collectSignals().
 */
export function auditDocument(signals, profileName = 'edge') {
  const profile = PROFILES[profileName] ?? PROFILES.edge;
  const violations = [];
  const warnings = [];
  for (const rule of DOCUMENT_RULES) {
    const failure = rule.evaluate(signals, profile);
    if (!failure) continue;
    const entry = { id: rule.id, source: rule.source, message: failure };
    if (rule.severity === 'critical') violations.push(entry);
    else warnings.push(entry);
  }
  return { violations, warnings, passes: violations.length === 0 };
}
